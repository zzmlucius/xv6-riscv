uint64
sys_exit(void)
{
  int n;
  argint(0, &n);
  kexit(n);
  return 0; // not reached
}

uint64
sys_getpid(void)
{
  return myproc()->pid;
}

uint64
sys_fork(void)
{
  return kfork();
}

uint64
sys_wait(void)
{
  uint64 p;
  argaddr(0, &p);
  return kwait(p);
}

uint64
sys_sbrk(void)
{
  uint64 addr;
  int t;
  int n;

  argint(0, &n);
  argint(1, &t);
  addr = myproc()->sz;

  if (t == SBRK_EAGER || n < 0) {
    if (growproc(n) < 0) {
      return -1;
    }
  } else {
    // Lazily allocate memory for this process: increase its memory
    // size but don't allocate memory. If the processes uses the
    // memory, vmfault() will allocate it.
    if (addr + n < addr)
      return -1;
    if (addr + n > USYSCALL)
      return -1;
    myproc()->sz += n;
  }
  return addr;
}

uint64
sys_pause(void)
{
  int n;
  uint ticks0;

  argint(0, &n);
  if (n < 0)
    n = 0;
  acquire(&tickslock);
  ticks0 = ticks;
  while (ticks - ticks0 < n) {
    if (killed(myproc())) {
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

uint64
sys_kill(void)
{
  int pid;

  argint(0, &pid);
  return kkill(pid);
}

// return how many clock tick interrupts have occurred
// since start.
uint64
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

uint64
sys_trace(void) // sys_trace implementation
{
  // 只有当前进程会访问 p->mask,所以不用lock
  int mask;
  
  // RISC-V ABI 规定 一开始user.h/trace()第一个参数放在a0寄存器
  argint(0, &mask); 
  
  struct proc *p = myproc();
  p->mask = mask;
  return 0;
}

uint64 
sys_info(void) { // 遍历freelist和proc[NPROC]数组
  struct sysinfo kif;
  uint64 ifp;
  
  argaddr(0, &ifp); // 拿过来的用户态的地址
  
  kif.freemem  = freemem();
  kif.nproc    = nproc();

  if(copyout(myproc() -> pagetable, ifp, (char*)&kif, sizeof(kif)) < 0)
    return -1;

  return 0;
}